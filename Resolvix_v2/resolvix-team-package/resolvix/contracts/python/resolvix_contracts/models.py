"""
Resolvix shared contracts — v1.0.0 (FROZEN at contract freeze).

Single source of truth for every payload that crosses a component boundary:
  A (voice-runtime)  <->  B (brain)     : in-process Python, Brain protocol + BrainEvent stream
  A (voice-runtime)  <->  C (ops-api)   : HTTP JSON (see contracts/openapi/ops-api.yaml)
  C (ops-api)        <->  B (brain)     : KBExport JSON (file or URL)

Rules
- Do NOT edit this file without agreement from all three members. Bump CONTRACT_VERSION on any change.
- All models forbid unknown fields, so drift fails loudly in tests.
"""
from __future__ import annotations

from datetime import date, datetime
from enum import Enum
from typing import Annotated, Literal, Union

from pydantic import BaseModel, ConfigDict, Field

CONTRACT_VERSION = "1.0.0"

# Placeholder that B (brain) puts inside speech text when a ticket ID is not yet known.
# A (voice-runtime) executes the blocking create_ticket action, then replaces this token
# with speak_ticket_id(ticket_id, lang) before sending the text to TTS.
TICKET_ID_PLACEHOLDER = "{{ticket_id}}"


class Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", use_enum_values=True)


# --------------------------------------------------------------------------- enums
class Lang(str, Enum):
    hi = "hi"
    en = "en"
    hinglish = "hinglish"


class Tier(str, Enum):
    confident = "confident"   # fully covered by KB, validated, cited
    partial = "partial"       # partly covered; doubt stated; human offered
    escalate = "escalate"     # not answerable / urgent / human needed
    chitchat = "chitchat"     # greeting, thanks, small talk
    clarify = "clarify"       # one detail needed before answering


class Path(str, Enum):
    safety = "safety"
    faq = "faq"
    llm = "llm"
    slot_filling = "slot_filling"
    escalation = "escalation"
    fallback = "fallback"


class Priority(str, Enum):
    P1 = "P1"  # emergency / exam within 60 min — immediate transfer + staff alert
    P2 = "P2"  # deadline today/tomorrow and caller blocked — transfer in hours, else callback
    P3 = "P3"  # complaint / unanswered question with no near deadline — normal queue
    P4 = "P4"  # routine information — no ticket unless unanswered


class TicketType(str, Enum):
    EMERGENCY = "EMERGENCY"
    URGENT = "URGENT"
    KNOWLEDGE_GAP = "KNOWLEDGE_GAP"
    COMPLAINT = "COMPLAINT"
    HUMAN_REQUEST = "HUMAN_REQUEST"
    SYSTEM_FAILURE = "SYSTEM_FAILURE"


class TicketStatus(str, Enum):
    open = "open"
    in_progress = "in_progress"
    resolved = "resolved"
    closed = "closed"


class CallChannel(str, Enum):
    pstn = "pstn"
    web = "web"
    test = "test"  # typed-input test page / harness


class CallOutcome(str, Enum):
    answered = "answered"
    escalated = "escalated"
    transferred = "transferred"
    emergency = "emergency"
    abandoned = "abandoned"
    failed = "failed"


# --------------------------------------------------------------------------- knowledge base
class KBEntry(Strict):
    id: str = Field(pattern=r"^[A-Z]{2,4}-\d{3,4}$", examples=["FEE-012"])
    department: str = Field(examples=["accounts"])
    question_variants: list[str] = Field(min_length=1)
    answer_en: str
    answer_hi: str | None = None
    source_title: str = Field(examples=["Fee Notice 2026-27"])
    source_ref: str | None = Field(default=None, examples=["p.1", "https://college.example/notice/12"])
    valid_from: date | None = None
    valid_until: date | None = None
    tags: list[str] = []
    is_faq: bool = False
    status: Literal["draft", "approved", "archived"] = "approved"


class KBExport(Strict):
    """C -> B. Only status=approved entries are included."""
    version_label: str
    exported_at: datetime
    entries: list[KBEntry]


class KBSource(Strict):
    kind: Literal["file", "url"]
    location: str  # path to kb.jsonl / KBExport json, or http URL to GET /v1/kb/export


class KBVersionInfo(Strict):
    kb_version: str = Field(description="first 12 hex chars of sha256 of the compiled prefix")
    entry_count: int
    faq_count: int
    token_count: int
    activated_at: datetime
    warnings: list[str] = []


# --------------------------------------------------------------------------- brain interface (A <-> B)
class ChatMessage(Strict):
    role: Literal["system", "user", "assistant"]
    content: str


class TicketRef(Strict):
    ticket_id: str
    type: TicketType
    status: TicketStatus
    department: str
    summary: str
    created_at: datetime


class CallContext(Strict):
    call_id: str
    channel: CallChannel
    caller_number: str | None = None  # E.164 or None (web/test)
    started_at: datetime
    open_tickets: list[TicketRef] = []  # P1 feature: repeat-caller memory


class CallStartPlan(Strict):
    kb_version: str
    greeting_text: str
    greeting_lang: Lang
    interruptable: bool = False


class TurnRequest(Strict):
    call_id: str
    turn_index: int = Field(ge=0)
    user_text: str
    history: list[ChatMessage] = []
    dtmf: str | None = None  # "0" = human request, if the runtime can capture DTMF
    received_at: datetime


class UrgencyFacts(Strict):
    event_type: Literal[
        "exam", "fee_deadline", "form_deadline", "admit_card", "safety", "medical",
        "harassment", "complaint", "other", "none"
    ] = "none"
    minutes_to_event: int | None = None
    blocked: bool = False          # caller cannot proceed without help
    safety_flag: bool = False      # safety / medical / harassment statement
    affected: Literal["self", "ward", "other"] | None = None


class TicketCreate(Strict):
    """A -> C (POST /v1/tickets). Built by B inside a CreateTicketAction."""
    idempotency_key: str
    call_id: str | None = None
    type: TicketType
    priority: Priority
    priority_reason: str = Field(description="rule id + human-readable reason, e.g. 'R-EXAM-60: exam in 15 min, caller blocked'")
    department: str
    summary: str = Field(max_length=280)
    collected_fields: dict[str, str] = {}
    caller_number: str | None = None
    callback_number: str | None = None
    callback_requested: bool = False
    transcript_excerpt: str = ""
    brief: str = Field(default="", description="2-4 line staff brief shown before pickup")


# ---- actions emitted by B, executed by A
class CreateTicketAction(Strict):
    kind: Literal["create_ticket"] = "create_ticket"
    ticket: TicketCreate


class TransferAction(Strict):
    kind: Literal["transfer"] = "transfer"
    department: str
    to_number: str           # E.164, resolved by B from departments.yaml (office hours applied)
    reason: str
    brief: str
    requires_ticket: bool = True  # ticket-first rule: A must not dial before ticket exists


class SendSmsAction(Strict):
    kind: Literal["send_sms"] = "send_sms"
    idempotency_key: str     # f"{call_id}:{template_id}:{to_number}"
    to_number: str
    template_id: Literal["ticket_created", "answer_copy", "staff_alert", "status_change"]
    vars: dict[str, str]     # may contain "ticket_id": TICKET_ID_PLACEHOLDER
    consent: Literal["caller_requested", "offer_accepted", "transactional", "staff"]


class LogGapAction(Strict):
    kind: Literal["log_gap"] = "log_gap"
    question: str
    lang: Lang
    department_guess: str | None = None


class ScheduleCallbackAction(Strict):  # P1
    kind: Literal["schedule_callback"] = "schedule_callback"
    to_number: str
    not_before: datetime | None = None
    reason: str


class EndCallAction(Strict):
    kind: Literal["end_call"] = "end_call"
    reason: str


Action = Annotated[
    Union[CreateTicketAction, TransferAction, SendSmsAction, LogGapAction, ScheduleCallbackAction, EndCallAction],
    Field(discriminator="kind"),
]


class TurnSummary(Strict):
    call_id: str
    turn_index: int
    path: Path
    tier: Tier | None = None
    lang: Lang
    kb_ids: list[str] = []
    urgency: UrgencyFacts | None = None
    priority: Priority | None = None
    priority_reason: str | None = None
    rule_id: str | None = None
    user_text_redacted: str
    assistant_text: str
    validator_flags: list[str] = []   # e.g. ["citation_invalid", "number_not_in_source", "json_retry"]
    latency_ms: dict[str, int] = {}   # keys: safety, faq, llm_ttft, llm_total, brain_total
    cached_tokens: int | None = None
    created_at: datetime


# ---- the event stream B yields for every turn
class MetaEvent(Strict):
    type: Literal["meta"] = "meta"
    path: Path
    tier: Tier | None = None
    lang: Lang
    interruptable: bool = True


class SpeechEvent(Strict):
    type: Literal["speech"] = "speech"
    text: str


class ActionEvent(Strict):
    type: Literal["action"] = "action"
    action: Action
    blocking: bool = False  # A must finish this action before streaming the next speech event


class DoneEvent(Strict):
    type: Literal["done"] = "done"
    summary: TurnSummary


BrainEvent = Annotated[Union[MetaEvent, SpeechEvent, ActionEvent, DoneEvent], Field(discriminator="type")]


# --------------------------------------------------------------------------- ops-api records (A <-> C, dashboard)
class CallStart(Strict):
    call_id: str
    channel: CallChannel
    caller_number: str | None = None
    started_at: datetime
    kb_version: str
    lang: Lang = Lang.hinglish


class CallEnd(Strict):
    ended_at: datetime
    outcome: CallOutcome
    ai_resolved: bool
    turns_count: int


class Ticket(Strict):
    ticket_id: str = Field(pattern=r"^[A-Z]{2}-\d{4}$", examples=["EX-1042"])
    call_id: str | None = None
    type: TicketType
    priority: Priority
    priority_reason: str
    department: str
    status: TicketStatus = TicketStatus.open
    summary: str
    collected_fields: dict[str, str] = {}
    caller_number: str | None = None
    callback_number: str | None = None
    callback_requested: bool = False
    transcript_excerpt: str = ""
    brief: str = ""
    assignee: str | None = None
    notes: list[str] = []
    created_at: datetime
    updated_at: datetime
    resolved_at: datetime | None = None


class TicketCreated(Strict):
    ticket_id: str
    created: bool  # False when the idempotency key matched an existing ticket


class TicketPatch(Strict):
    status: TicketStatus | None = None
    assignee: str | None = None
    note: str | None = None
    resolution: str | None = None


class TicketEvent(Strict):
    kind: Literal[
        "transfer_attempted", "transfer_connected", "transfer_failed",
        "sms_queued", "sms_sent", "sms_failed", "sms_suppressed",
        "status_changed", "note_added", "callback_scheduled", "brief_pushed"
    ]
    payload: dict[str, str] = {}
    actor: str = "system"
    at: datetime


class SmsRequest(Strict):
    idempotency_key: str
    to_number: str
    template_id: Literal["ticket_created", "answer_copy", "staff_alert", "status_change"]
    vars: dict[str, str]
    consent: Literal["caller_requested", "offer_accepted", "transactional", "staff"]
    call_id: str | None = None
    ticket_id: str | None = None


class SmsResult(Strict):
    message_id: str
    status: Literal["queued", "sent", "delivered", "failed", "suppressed"]
    mode: Literal["live", "mock"]
    reason: str | None = None  # why suppressed / failed


class GapCreate(Strict):
    question: str
    lang: Lang
    department_guess: str | None = None
    call_id: str | None = None
    ticket_id: str | None = None


class GapCluster(Strict):
    cluster_id: str
    label: str
    department: str | None
    count: int
    examples: list[str]
    last_seen: datetime
    status: Literal["new", "needs_document", "answered", "ignored"]


# --------------------------------------------------------------------------- errors
class ErrorBody(Strict):
    code: Literal[
        "validation_error", "not_found", "conflict", "unauthorized", "rate_limited",
        "upstream_error", "timeout", "internal"
    ]
    message: str
    retryable: bool = False
    details: dict[str, str] = {}


class ErrorEnvelope(Strict):
    error: ErrorBody


# --------------------------------------------------------------------------- shared config
class OfficeHours(Strict):
    days: list[Literal["mon", "tue", "wed", "thu", "fri", "sat", "sun"]]
    open: str = Field(pattern=r"^\d{2}:\d{2}$")
    close: str = Field(pattern=r"^\d{2}:\d{2}$")


class Department(Strict):
    key: str
    name: str
    ticket_prefix: str = Field(pattern=r"^[A-Z]{2}$")
    transfer_numbers: list[str]  # E.164, dialled in order (~20 s each)
    sms_alert_numbers: list[str] = []
    hours: list[OfficeHours]
    topics: list[str] = []
    mvp: bool = True


class DepartmentsConfig(Strict):
    timezone: str = "Asia/Kolkata"
    default_department: str
    emergency: dict[str, list[str]]  # {"transfer_numbers": [...], "sms_alert_numbers": [...], "public_numbers": [...]}
    departments: list[Department]
